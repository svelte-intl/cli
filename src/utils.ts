import pc from 'picocolors';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';

export type Dictionary = Record<string, string>;

/** Only http(s) URLs count. Paths like `C:\project\en.json` are files. */
export function isURL(input: string): boolean {
    try {
        const { protocol } = new URL(input);
        return protocol === 'http:' || protocol === 'https:';
    } catch {
        return false;
    }
}

/** Reads JSON from a file path or an http(s) URL. Errors name the input. */
export async function loadJSON(input: string, cwd = process.cwd()): Promise<unknown> {
    let text: string;

    if (isURL(input)) {
        let response: Response;
        try {
            response = await fetch(input, { signal: AbortSignal.timeout(15_000) });
        } catch (error) {
            const { cause } = error as { cause?: { code?: string; message?: string } };
            const reason = cause?.code ?? cause?.message;
            throw new Error(
                `Could not fetch ${input}: ${message(error)}${reason ? ` (${reason})` : ''}`,
            );
        }
        if (!response.ok) {
            throw new Error(
                `Could not fetch ${input}: HTTP ${response.status} ${response.statusText}`.trim(),
            );
        }
        text = await response.text();
    } else {
        try {
            text = await readFile(resolve(cwd, input), 'utf-8');
        } catch (error) {
            throw new Error(`Could not read ${input}: ${message(error)}`);
        }
    }

    try {
        return JSON.parse(text);
    } catch (error) {
        throw new Error(`${input} is not valid JSON: ${message(error)}`);
    }
}

/**
 * Checks that the value is a flat `Record<string, string>`.
 * Returns readable problems, one per offending key.
 */
export function validateDictionary(
    value: unknown,
): { dictionary: Dictionary } | { problems: string[] } {
    if (typeof value !== 'object' || value === null || Array.isArray(value)) {
        const kind = Array.isArray(value)
            ? 'an array'
            : value === null
              ? 'null'
              : `a ${typeof value}`;
        return { problems: [`Expected an object of translations, got ${kind}.`] };
    }

    const problems: string[] = [];
    for (const [key, entry] of Object.entries(value)) {
        if (typeof entry === 'string') continue;
        if (typeof entry === 'object' && entry !== null && !Array.isArray(entry)) {
            const child = Object.keys(entry)[0] ?? 'key';
            problems.push(
                `${JSON.stringify(key)} is a nested object. Dictionaries must be flat: use keys like ${JSON.stringify(`${key}.${child}`)}.`,
            );
        } else {
            const kind = Array.isArray(entry)
                ? 'an array'
                : entry === null
                  ? 'null'
                  : `a ${typeof entry}`;
            problems.push(`${JSON.stringify(key)} must be a string, got ${kind}.`);
        }
    }

    return problems.length ? { problems } : { dictionary: value as Dictionary };
}

/** Renders the declaration file. Same format as `@svelte-i18n/core/vite`. */
export function renderTypes(keys: Iterable<string>, typeName = 'I18nDictionary'): string {
    const lines = [...new Set(keys)].sort().map((key) => `\t${JSON.stringify(key)}: string;`);
    return [
        '// Generated by @svelte-i18n/cli. Do not edit.',
        `export type ${typeName} = {`,
        ...lines,
        '};',
        '',
    ].join('\n');
}

export const message = (error: unknown) => (error instanceof Error ? error.message : String(error));

export const success = (text: string) => console.log(pc.green(`✔ ${text}`));

/** Animated spinner on a TTY. In CI and pipes it prints nothing, so logs stay clean. */
export function spinner(text: string, stream: NodeJS.WriteStream = process.stdout) {
    if (!stream.isTTY) return () => {};

    const frames = ['⣾', '⣷', '⣯', '⣟', '⣻', '⣽'];
    let i = 0;
    const interval = setInterval(() => {
        stream.write(`\r${pc.greenBright(frames[i])} ${pc.cyan(text)}`);
        i = (i + 1) % frames.length;
    }, 100);

    return () => {
        clearInterval(interval);
        stream.write('\r\x1b[2K');
    };
}
